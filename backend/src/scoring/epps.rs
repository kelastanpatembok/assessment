pub fn score(
    answers: &BTreeMap<i32, String>,
    female: bool,
) -> Result<(BTreeMap<String, TraitScore>, i32, i32), String> {
    if answers.len() != 225 {
        return Err("Harap jawab seluruh 225 pernyataan EPPS.".to_string());
    }
    for no in 1..=225 {
        match answers.get(&no).map(String::as_str) {
            Some("A") | Some("B") => {}
            _ => return Err(format!("Jawaban nomor {no} harus A atau B.")),
        }
    }

    let mut raw: BTreeMap<String, i32> = TRAITS.iter().map(|k| ((*k).to_string(), 0)).collect();
    for (code, a_questions, b_questions) in SCORE_KEY {
        let score = a_questions
            .iter()
            .filter(|no| answers.get(no).is_some_and(|answer| answer == "A"))
            .count()
            + b_questions
                .iter()
                .filter(|no| answers.get(no).is_some_and(|answer| answer == "B"))
                .count();
        raw.insert(code.to_string(), score as i32);
    }

    let mut result = BTreeMap::new();
    for (code, label, male, women) in NORMS {
        let value = *raw.get(code).expect("known trait");
        result.insert(
            code.to_string(),
            TraitScore {
                label: label.to_string(),
                raw: value,
                percentile: (if female { women } else { male })[value as usize],
            },
        );
    }
    let consistency_pairs = [
        (1, 151),
        (7, 157),
        (13, 163),
        (19, 169),
        (25, 175),
        (26, 101),
        (32, 107),
        (38, 113),
        (44, 119),
        (50, 125),
        (51, 201),
        (57, 207),
        (63, 213),
        (69, 219),
        (75, 225),
    ];
    let consistency_raw = consistency_pairs
        .iter()
        .filter(|(a, b)| answers.get(a) == answers.get(b))
        .count() as i32;
    let consistency_percentile = (if female {
        CONSISTENCY_FEMALE
    } else {
        CONSISTENCY_MALE
    })[consistency_raw as usize];
    Ok((result, consistency_raw, consistency_percentile))
}

#[derive(Debug, Clone)]
pub struct TraitScore {
    pub label: String,
    pub raw: i32,
    pub percentile: i32,
}
